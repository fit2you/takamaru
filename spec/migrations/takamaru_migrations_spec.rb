require 'rails_helper'

require 'generators/takamaru/install/install_generator'
require 'generators/takamaru/upgrade/upgrade_generator'

# The migrations run inside the example transaction: PostgreSQL rolls back the schema changes too.
RSpec.describe('Takamaru migrations') do
  let(:connection) { ActiveRecord::Base.connection }

  around do |example|
    ActiveRecord::Migration.verbose = false
    Dir.mktmpdir { |dir| @destination = dir and example.run }
  end

  def generate_migration(generator, name)
    generator.start(['--quiet'], destination_root: @destination)
    load(Dir[File.join(@destination, "db/migrate/*_#{name}.rb")].sole)
    name.camelize.constantize.new
  end

  def commit_log_rows
    connection.select_all('SELECT message_id, published_at, attempts FROM takamaru_commit_logs').to_a
  end

  describe 'takamaru:install' do
    it 'creates the commit log table' do
      connection.drop_table(:takamaru_commit_logs)

      generate_migration(Takamaru::InstallGenerator, 'create_takamaru_commit_logs').migrate(:up)

      expect(connection.column_exists?(:takamaru_commit_logs, :message_id, :uuid, null: false)).to(be(true))
      expect(connection.index_exists?(:takamaru_commit_logs, :message_id, unique: true)).to(be(true))
      expect(connection.index_name_exists?(:takamaru_commit_logs, 'index_takamaru_commit_logs_pending')).to(be(true))
    end
  end

  describe 'takamaru:upgrade' do
    before do
      connection.drop_table(:takamaru_commit_logs)
      # The table generated by takamaru 0.x, with a row not published yet
      connection.create_table(:takamaru_commit_logs) do |t|
        t.string(:exchange_name, null: false)
        t.json(:payload, null: false)
        t.timestamps
      end
      connection.execute(<<~SQL)
        INSERT INTO takamaru_commit_logs (exchange_name, payload, created_at, updated_at)
        VALUES ('app.users', '{"id":1,"event":"update"}', now(), now())
      SQL
    end

    let(:migration) { generate_migration(Takamaru::UpgradeGenerator, 'upgrade_takamaru_commit_logs_to_v1') }

    it 'upgrades the table and keeps the existing rows pending' do
      migration.migrate(:up)

      expect(connection.column_exists?(:takamaru_commit_logs, :message_id, :uuid, null: false)).to(be(true))
      expect(connection.index_exists?(:takamaru_commit_logs, :message_id, unique: true)).to(be(true))
      expect(connection.index_name_exists?(:takamaru_commit_logs, 'index_takamaru_commit_logs_pending')).to(be(true))
      expect(commit_log_rows).to(contain_exactly(
        'attempts' => 0,
        'message_id' => match(/\A\h{8}-\h{4}-\h{4}-\h{4}-\h{12}\z/),
        'published_at' => nil,
      ))
    end

    it 'can be rolled back' do
      migration.migrate(:up)
      migration.migrate(:down)

      expect(connection.columns(:takamaru_commit_logs).map(&:name))
        .to(contain_exactly('id', 'exchange_name', 'payload', 'created_at', 'updated_at'))
    end
  end
end
